"""
Модуль класса Converter (Практическое задание: Срез знаний по юнит-тестам).
"""


class Converter:
    """
    Класс Converter с единственным статическим методом do(x: float) -> int.
    """

    @staticmethod
    def do(x: float) -> int:
        """
        Принимает вещественное число float (с точностью 1 знак после запятой)
        и возвращает целое число int по следующему алгоритму:

        * x ∈ [100.7; +∞)   -> 1000
        * x ∈ (0; 100.7)    -> int(x) (отбрасывание дробной части)
        * x == 0.0          -> генерируется исключение ValueError
        * x ∈ [-30.4; 0)    -> int(x) - 5
        * x ∈ (-∞; -30.5]   -> -2000

        Параметры:
            x (float): Входное вещественное число.

        Возвращает:
            int: Результат вычисления согласно интервалу.

        Исключения:
            TypeError: Если аргумент не является числом или передан bool.
            ValueError: Если x == 0.0.
        """
        # Проверка типа входных данных
        if not isinstance(x, (int, float)) or isinstance(x, bool):
            raise TypeError(
                f"Аргумент x должен быть числом с плавающей точкой (float), "
                f"получен тип: {type(x).__name__}"
            )

        # Округление до 1 знака после запятой согласно спецификации ТЗ
        x_val = round(float(x), 1)

        # Точка x == 0.0
        if x_val == 0.0:
            raise ValueError("Значение x не может быть равно 0.0")

        # Диапазон [100.7; +∞)
        if x_val >= 100.7:
            return 1000

        # Диапазон (0; 100.7)
        if 0.0 < x_val < 100.7:
            return int(x_val)

        # Диапазон (-∞; -30.5]
        if x_val <= -30.5:
            return -2000

        # Диапазон [-30.4; 0)
        if -30.4 <= x_val < 0.0:
            return int(x_val) - 5

        # Защитное значение для чисел в интервале (-30.5; -30.4)
        return -2000
